-- Мультитенантность: каждая существующая задача относится к тенанту 'default'.
-- Значение по умолчанию убирается сразу после backfill, чтобы новые строки
-- обязаны явно указывать тенанта.
ALTER TABLE tasks ADD COLUMN tenant_id VARCHAR(64) DEFAULT 'default' NOT NULL;
ALTER TABLE tasks ALTER COLUMN tenant_id DROP DEFAULT;

-- Мягкое удаление: NULL — задача активна, timestamp — удалена.
ALTER TABLE tasks ADD COLUMN deleted_at TIMESTAMP WITH TIME ZONE;

CREATE INDEX idx_tasks_tenant_created ON tasks (tenant_id, created_at);
CREATE INDEX idx_tasks_tenant_status ON tasks (tenant_id, status);

-- Журнал аудита: только добавление, переживает мягкое удаление задачи.
CREATE TABLE task_events
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   VARCHAR(64)              NOT NULL,
    task_id     BIGINT                   NOT NULL,
    type        VARCHAR(32)              NOT NULL,
    from_status VARCHAR(32),
    to_status   VARCHAR(32),
    actor       VARCHAR(64)              NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_task_events_type CHECK (type IN ('CREATED', 'UPDATED', 'STATUS_CHANGED', 'DELETED'))
);

CREATE INDEX idx_task_events_tenant_task ON task_events (tenant_id, task_id, occurred_at);

-- Идемпотентность создания: один ключ на тенанта.
CREATE TABLE idempotency_keys
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(64)              NOT NULL,
    idem_key   VARCHAR(128)             NOT NULL,
    task_id    BIGINT                   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_tenant_key UNIQUE (tenant_id, idem_key)
);
